# 155. Min Stack (Easy) — Day 3, 2026-11-21
# Idea: keep a parallel stack of running minimums; push to it whenever
# the new value is <= the current minimum.
class MinStack:
    def __init__(self):
        self.stack = []
        self.min_stack = []

    def push(self, val: int) -> None:
        self.stack.append(val)
        if not self.min_stack or val <= self.min_stack[-1]:
            self.min_stack.append(val)

    def pop(self) -> None:
        val = self.stack.pop()
        if val == self.min_stack[-1]:
            self.min_stack.pop()

    def top(self) -> int:
        return self.stack[-1]

    def getMin(self) -> int:
        return self.min_stack[-1]
# Time: O(1) per operation | Space: O(n)
